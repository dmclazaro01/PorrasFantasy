// Service worker mínimo: network-first (siempre contenido fresco online,
// con caché de respaldo para funcionar offline). Su presencia + el manifest
// es lo que hace que el navegador ofrezca "Instalar app".
const CACHE = 'porra-v1'

self.addEventListener('install', () => self.skipWaiting())
self.addEventListener('activate', (e) => e.waitUntil(self.clients.claim()))

self.addEventListener('fetch', (event) => {
  const req = event.request
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return
  event.respondWith(
    fetch(req)
      .then((res) => {
        const copy = res.clone()
        caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => {})
        return res
      })
      .catch(() => caches.match(req).then((r) => r || caches.match('/'))),
  )
})
